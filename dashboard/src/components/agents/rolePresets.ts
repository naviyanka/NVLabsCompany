/**
 * Get pre-filled role preset for a given role identifier.
 * Returns default values if exact role is not found.
 */
export function getRolePreset(roleId: string): RolePreset {
  const normalized = (roleId || '').toLowerCase().trim();

  if (ROLE_PRESETS[normalized]) {
    return ROLE_PRESETS[normalized];
  }

  // Generic fallback if role is custom or unrecognized
  const titleFormatted = roleId
    ? roleId.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ')
    : 'Specialist';

  return {
    title: `${titleFormatted} Specialist`,
    capabilities: `${normalized}, execution, problem-solving`,
    responsibilities: `Executes operational tasks assigned within the ${titleFormatted} domain.`,
    objectives: `Deliver high-quality work with fast execution velocity and low defect rate.`,
    personalityTraits: 'detail-oriented, analytical, pragmatic, collaborative',
    communicationStyle: 'structured, clear, professional',
    agentValues: 'correctness, efficiency, reliability, team-success',
    agentConstraints: 'must verify work before completion\nfollow team engineering standards',
    tone: 'professional',
    soulDescription: `Pragmatic ${titleFormatted} agent focused on executing domain objectives with discipline and high technical standards.`,
  };
}
